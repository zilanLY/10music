/**
 * 构建 Netlify Function 的静态模块索引
 * 把 ncm-api/module/ 下所有 JS 文件编译成一个带显式 require 的文件，
 * 这样 esbuild 就能正确 trace 所有依赖。
 * 跳过 require 时出错的模块以及已知 esbuild 不兼容的模块。
 */
const fs = require('fs')
const path = require('path')

const repoRoot = path.resolve(__dirname, '..')
const moduleDir = path.join(repoRoot, 'netlify/functions/ncm-api/module')
const outFile = path.join(repoRoot, 'netlify/functions/_modules.js')

// 已知在 esbuild 环境下无法解析的模块
const ESBUILD_BLACKLIST = new Set([
  'song_url_v1.js',   // 依赖 @neteasecloudmusicapienhanced/unblockmusic-utils, dotenv
  'cloud.js',         // 依赖 music-metadata (ESM-only，require 不可用)
])

// Netlify 专用替换：黑名单模块的替代实现
const NETLIFY_REPLACEMENTS = {
  '/song/url/v1': "require('./ncm-api/module/song_url_v1_netlify.js')",
}

// 先初始化 global.deviceId
try {
  const { generateDeviceId } = require(path.join(repoRoot, 'netlify/functions/ncm-api/util/index'))
  global.deviceId = generateDeviceId()
} catch (_) {}

const files = fs.readdirSync(moduleDir).filter(f => f.endsWith('.js')).sort()

const loaded = []
const skipped = []

for (const file of files) {
  if (ESBUILD_BLACKLIST.has(file)) {
    skipped.push({ file, error: 'esbuild-incompatible (blacklisted)' })
    continue
  }
  const fullPath = path.join(moduleDir, file)
  try {
    require(fullPath)
    loaded.push(file)
  } catch (e) {
    skipped.push({ file, error: e.message.split('\n')[0] })
  }
}

// 生成带有静态 require 的模块文件
const lines = [
  '// Auto-generated by scripts/build-netlify-modules.js',
  '// DO NOT EDIT — generated at ' + new Date().toISOString(),
  '// Contains static require() for ' + loaded.length + ' API modules',
  '// (' + skipped.length + ' skipped due to missing/incompatible dependencies)',
  '',
  'module.exports = {',
]

for (const file of loaded) {
  const name = file.slice(0, -3)
  const route = name.replace(/_/g, '/')
  lines.push(`  '/${route}': require('./ncm-api/module/${file}'),`)
}

// 注入 Netlify 专用替换模块
for (const [route, req] of Object.entries(NETLIFY_REPLACEMENTS)) {
  lines.push(`  '${route}': ${req},`)
}

lines.push('}')
lines.push('')

const content = lines.join('\n')
fs.writeFileSync(outFile, content, 'utf-8')

console.log(`[build-netlify-modules] 已生成 ${outFile}`)
console.log(`  已加载: ${loaded.length} 个模块`)
if (skipped.length > 0) {
  console.log(`  跳过: ${skipped.length} 个模块:`)
  skipped.forEach(s => console.log(`    - ${s.file}: ${s.error}`))
}
