/**
 * build-ncm-modules.js
 * 
 * 构建脚本：把 api-enhanced 的 CommonJS 模块
 * 转换为 Cloudflare Workers 可用的 ES Module 绑定包。
 *
 * 用法：node scripts/build-ncm-modules.js
 * 输出：functions/api/ncm-modules.ts
 */

const fs   = require('fs')
const path = require('path')

const MODULES_DIR  = path.join(__dirname, '../server/ncm-api/module')
const OUTPUT_FILE = path.join(__dirname, '../functions/api/ncm-modules.ts')

// ── 特殊路由（api-enhanced server.js 中的硬编码）────────────
const SPECIAL_FILES = new Map([
  ['daily_signin.js',  'daily_signin'],
  ['fm_trash.js',     'fm_trash'],
  ['personal_fm.js',   'personal_fm'],
])

// ── 把文件名映射为路由 ─────────────────────────────────────
function fileToRoute(file) {
  const name = file.replace(/\.js$/, '')
  if (SPECIAL_FILES.has(file)) return SPECIAL_FILES.get(file)
  return name.replace(/_/g, '/')
}

// ── 把 CommonJS 模块源码转换为 ES Module 兼容格式 ─────────
function transformModuleSource(file, source) {
  // 1. module.exports = ...  →  export default ...
  let code = source.replace(/module\.exports\s*=\s*/, 'export default ')

  // 2. require('../util/xxx.js')  →  需要处理，但构建时我们会把 util 也内联
  //    这里先改成相对路径的 import（构建后再处理）
  code = code.replace(
    /require\(['"](?:\.\.\/util\/)?([^'"]+)['"]\)/g,
    (_, m) => {
      // 简单处理：如果是 createOption 这种 util 引用，先保留为占位
      return `__util['${m.replace(/\.js$/, '')}']`
    }
  )

  return code
}

// ── 主逻辑 ─────────────────────────────────────────────────
function build() {
  const files = fs.readdirSync(MODULES_DIR).filter(f => f.endsWith('.js'))

  let out = `// Auto-generated by build-ncm-modules.js — DO NOT EDIT\n`
  out += `// 构建时间: ${new Date().toISOString()}\n\n`

  // 1. 注入工具函数占位（运行时由 cloudflare request 函数提供）
  out += `// ── util 占位（由 createRequest 运行时注入）────────────────\n`
  out += `const __util: Record<string, any> = {}\n`
  out += `export function setUtil(util: Record<string, any>) { Object.assign(__util, util) }\n\n`

  // 2. 内联关键 util 函数（createOption 等）
  out += `// ── 内联 util ───────────────────────────────────────────\n`

  // 读取 util/option.js
  const optionPath = path.join(__dirname, '../server/ncm-api/util/option.js')
  if (fs.existsSync(optionPath)) {
    let optionSrc = fs.readFileSync(optionPath, 'utf8')
    // 去掉 require 行，只保留核心逻辑
    optionSrc = optionSrc.replace(/const [^=]+=\s*require\([^)]+\)\s*\n?/g, '')
    out += `// ── createOption (from util/option.js) ──\n`
    // 包装成函数导出
    out += `export function createOption(query: any, cryptoType: string) {\n`
    out += `  // ... 简化版：直接返回 { crypto, cookie, ... }\n`
    out += `  return {\n`
    out += `    crypto: cryptoType || 'weapi',\n`
    out += `    cookie: query.cookie || {},\n`
    out += `    ...query,\n`
    out += `  }\n`
    out += `}\n\n`
  }

  out += `// ── 模块导出 ─────────────────────────────────────────────\n`
  out += `export const modules: Record<string, (query: any, request: any) => Promise<any>> = {}\n\n`

  for (const file of files) {
    const route   = fileToRoute(file)
    const filePath = path.join(MODULES_DIR, file)
    const source   = fs.readFileSync(filePath, 'utf8')

    // 转换并内联模块代码
    let code = transformModuleSource(file, source)

    // 取函数体（export default (query, request) => { ... }）
    const fnMatch = code.match(/export default\s+(\(query[^]+)$/s)
    if (fnMatch) {
      out += `// ── ${route} (${file}) ──\n`
      out += `modules['${route}'] = ${fnMatch[1]}\n\n`
    } else {
      // 降级：整段输出
      out += `// ── ${route} (${file}) ──\n`
      out += `modules['${route}'] = ${code.replace(/^export default\s+/, '')}\n\n`
    }
  }

  out += `\nexport default modules\n`

  fs.writeFileSync(OUTPUT_FILE, out, 'utf8')
  console.log(`✅ 生成 ${OUTPUT_FILE}`)
  console.log(`   共 ${files.length} 个模块`)
}

build()
